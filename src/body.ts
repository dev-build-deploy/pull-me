import * as fs from "node:fs";
import * as path from "node:path";

import { ConventionalCommit } from "@dev-build-deploy/commit-it";

import { CheckRun } from "./gh.js";
import { GENERATED_END, GENERATED_START, normaliseHeading, parseBody } from "./markdown.js";

/** The skeleton of a description: the same text as the org-wide pull request template. */
export const TEMPLATE = `<!-- Write for a junior engineer new to this repo: plain words, short sentences, explain each term or
abbreviation the first time. State every fact yourself: an issue, decision or design doc may be linked,
but the text must say what it says. -->

## Why
<!-- The value: what we wanted to achieve, for whom, and which issue or decision asks for it. Not the diff. -->

## How
<!-- The implementation: the choices and why; what moved where. The file list is generated below. -->

## Review hints
<!-- Where the risk is, what to read first, known gaps, what is not covered. -->

## Proof
<!-- Evidence: test output in a fenced block, links to runs or artifacts, screenshots (pull-me attach). -->
`;

/** A commit on the branch: its short hash and subject. */
export interface CommitInfo {
  hash: string;
  subject: string;
}

/** A changed file with its added and removed line counts (undefined for binary files). */
export interface FileChange {
  path: string;
  added?: number;
  removed?: number;
}

/** What the generated block lists. */
export interface GeneratedInput {
  commits: CommitInfo[];
  files: FileChange[];
  /** Area name to glob (`"engine": "engine/**"`); files outside every area go by their top folder. */
  areas: Record<string, string>;
  /** The check runs on the head commit; undefined leaves the part out (`--no-checks`). */
  checks?: CheckRun[];
  head?: string;
}

/** Turns a glob with `*` and `**` into an anchored regular expression. */
export function globToRegExp(glob: string): RegExp {
  let out = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      out += ".*";
      i++;
      if (glob[i + 1] === "/") i++;
    } else if (c === "*") out += "[^/]*";
    else if (c === "?") out += "[^/]";
    else out += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${out}$`);
}

/** The area of a file: the first matching area glob, else its top folder, else "(root)". */
export function areaOf(file: string, areas: Record<string, string>): string {
  for (const [name, glob] of Object.entries(areas)) if (globToRegExp(glob).test(file)) return name;
  return file.includes("/") ? file.split("/")[0] : "(root)";
}

/** Groups commits by Conventional Commit type: feat, fix, then the other types alphabetically, then "other". */
export function groupCommits(commits: CommitInfo[]): [string, CommitInfo[]][] {
  const groups = new Map<string, CommitInfo[]>();
  for (const commit of commits) {
    const cc = ConventionalCommit.fromString({ hash: commit.hash, message: commit.subject });
    const type = cc.isValid && cc.type ? cc.type.toLowerCase() : "other";
    groups.set(type, [...(groups.get(type) ?? []), commit]);
  }
  const rank = (t: string): string => (t === "feat" ? "0" : t === "fix" ? "1" : t === "other" ? "3" : `2${t}`);
  return [...groups.entries()].sort(([a], [b]) => rank(a).localeCompare(rank(b)));
}

const count = (n?: number): string => (n === undefined ? "binary" : String(n));

/** The generated block: commits by type, changed files by area with line counts, and the checks. Sorted; no clock. */
export function generatedBlock(input: GeneratedInput): string {
  const out = [
    GENERATED_START,
    "<details>",
    "<summary>Generated by pull-me: commits, changed files and checks</summary>",
    "",
  ];
  out.push(`### Commits (${input.commits.length})`, "");
  for (const [type, commits] of groupCommits(input.commits)) {
    out.push(`**${type}**`, "");
    for (const c of commits) out.push(`- ${c.hash} ${c.subject}`);
    out.push("");
  }
  out.push(`### Changed files (${input.files.length})`, "");
  const byArea = new Map<string, FileChange[]>();
  for (const f of [...input.files].sort((a, b) => a.path.localeCompare(b.path))) {
    const area = areaOf(f.path, input.areas);
    byArea.set(area, [...(byArea.get(area) ?? []), f]);
  }
  for (const [area, files] of [...byArea.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const added = files.reduce((n, f) => n + (f.added ?? 0), 0);
    const removed = files.reduce((n, f) => n + (f.removed ?? 0), 0);
    out.push(`**${area}** (+${added} -${removed})`, "");
    for (const f of files) out.push(`- \`${f.path}\` +${count(f.added)} -${count(f.removed)}`);
    out.push("");
  }
  if (input.checks) {
    out.push(`### Checks${input.head ? ` on ${input.head.slice(0, 7)}` : ""}`, "");
    if (input.checks.length === 0) out.push("- none yet");
    for (const c of input.checks) out.push(`- [${c.name}](${c.url}): ${c.conclusion}`);
    out.push("");
  }
  out.push("</details>", GENERATED_END);
  return out.join("\n");
}

/** Replaces the generated block of a body, or appends it; everything the author wrote stays byte-identical. */
export function replaceGenerated(body: string, block: string): string {
  const start = body.indexOf(GENERATED_START);
  const end = body.indexOf(GENERATED_END, start);
  if (start >= 0 && end >= 0) return body.slice(0, start) + block + body.slice(end + GENERATED_END.length);
  return `${body.replace(/\s*$/, "")}\n\n${block}\n`;
}

/** The image types and the size limit of GitHub attachments. */
export const ATTACH_TYPES = [".png", ".jpg", ".jpeg", ".gif", ".webp", ".mp4", ".mov"];
export const ATTACH_MAX_BYTES = 10 * 1024 * 1024;

/** One file to attach: its path as given and its alt text (after `#`). */
export interface Attachment {
  path: string;
  alt: string;
}

/** Parses `file.png#alt text`; checks the type and the size. Throws an Error with the reason. */
export function parseAttachment(spec: string, cwd: string = process.cwd()): Attachment {
  const hash = spec.indexOf("#");
  const file = hash >= 0 ? spec.slice(0, hash) : spec;
  const alt = hash >= 0 ? spec.slice(hash + 1).trim() : path.basename(file, path.extname(file));
  const ext = path.extname(file).toLowerCase();
  if (!ATTACH_TYPES.includes(ext)) throw new Error(`${file}: only ${ATTACH_TYPES.join(", ")} can be attached`);
  const full = path.resolve(cwd, file);
  if (!fs.existsSync(full)) throw new Error(`${file}: no such file`);
  if (fs.statSync(full).size > ATTACH_MAX_BYTES)
    throw new Error(`${file}: larger than 10 MB, GitHub's limit for an attachment`);
  return { path: file.startsWith("./") || path.isAbsolute(file) ? file : `./${file}`, alt };
}

/**
 * Puts image references for the attachments under a `### Screenshots` subheading at the end of Proof (a Proof section
 * is added when there is none). gh replaces each local reference with the uploaded file's URL.
 */
export function insertScreenshots(body: string, attachments: Attachment[]): string {
  const images = attachments.map(a => `![${a.alt.replace(/[[\]]/g, "")}](${a.path})`);
  const parsed = parseBody(body);
  const lines = body.replace(/\r\n?/g, "\n").split("\n");
  const proof = parsed.sections.find(s => normaliseHeading(s.title) === "proof");
  if (!proof) return `${body.replace(/\s*$/, "")}\n\n## Proof\n\n### Screenshots\n\n${images.join("\n")}\n`;

  const after = parsed.sections.find(s => s.line > proof.line);
  let insertAt = (after ? after.line : lines.length + 1) - 1;
  // Before the generated block, when it closes the section.
  const generated = proof.lines.find(l => l.kind === "generated");
  if (generated) insertAt = Math.min(insertAt, generated.number - 1);
  while (insertAt > proof.line && lines[insertAt - 1].trim() === "") insertAt--;
  const hasHeading = proof.lines.some(l => /^###\s+screenshots\s*$/i.test(l.text.trim()));
  const block = [...(hasHeading ? [] : ["", "### Screenshots"]), "", ...images, ""];
  return [
    ...lines.slice(0, insertAt),
    ...block,
    ...lines.slice(insertAt).slice(lines[insertAt]?.trim() === "" ? 1 : 0),
  ].join("\n");
}
